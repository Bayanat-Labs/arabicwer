"""Write web/policies.js from the policy files in src/arabicwer/policies (the web page cannot fetch files).

Usage: python scripts/build_web.py [--check]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORDER = ["raw", "nfc", "dediac", "strict-orth", "bayanat-norm-v1", "lenient"]


def render():
    data = []
    for name in ORDER:
        with open(os.path.join(ROOT, "src", "arabicwer", "policies", name + ".json"), encoding="utf-8") as f:
            data.append(json.load(f))
    body = json.dumps(data, ensure_ascii=False, indent=1)
    return ("// Generated by scripts/build_web.py from src/arabicwer/policies/*.json. Do not edit.\n"
            "// Policy files: CC BY 4.0, Bayanat Labs.\n"
            f"export const POLICY_DATA = {body};\n")


def main(argv):
    out = os.path.join(ROOT, "web", "policies.js")
    text = render()
    if "--check" in argv:
        with open(out, encoding="utf-8") as f:
            if f.read() != text:
                print("web/policies.js is out of date; run scripts/build_web.py")
                return 1
        return 0
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
